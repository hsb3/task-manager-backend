#!/usr/bin/env bun
/**
 * Generate clients/tm/src/api.generated.ts — the typed API surface the tm CLI is built on — from
 * openapi.json, so the spec and the client change in the same PR (`--check` gates drift).
 *
 * Emits one interface per components.schemas entry, the collection names that have a
 * /api/collections/{name}/records path, and the custom routes with their methods.
 *
 * Usage: bun scripts/gen_tm_client.ts [--check]
 */

import fs from "node:fs";
import path from "node:path";
import * as prettier from "prettier";
import { parse_args } from "./_argparse.ts";
import { by_code_point, read_text } from "./_py.ts";

const REPO = path.dirname(path.dirname(path.resolve(import.meta.path)));
const SPEC = path.join(REPO, "openapi.json");
const OUTPUT = path.join(REPO, "clients", "tm", "src", "api.generated.ts");

const COLLECTION_PATH = /^\/api\/collections\/([a-z_]+)\/records$/;

/** JSON Schema fragment -> TypeScript type text. Unknown shapes become `unknown`, never `any`. */
export function ts_type(schema: any): string {
  if (!schema || typeof schema !== "object") return "unknown";
  if (schema.$ref) return String(schema.$ref).split("/").pop()!;
  if (Array.isArray(schema.enum))
    return schema.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${ts_type(schema.items)}[]`;
    case "object": {
      const props = schema.properties ?? {};
      const required = new Set<string>(schema.required ?? []);
      const names = Object.keys(props).sort(by_code_point);
      if (!names.length) return "Record<string, unknown>";
      const body = names
        .map((n) => `${JSON.stringify(n)}${required.has(n) ? "" : "?"}: ${ts_type(props[n])};`)
        .join(" ");
      return `{ ${body} }`;
    }
    default:
      return "unknown";
  }
}

export function render(spec: any): string {
  const out: string[] = [
    "// GENERATED by scripts/gen_tm_client.ts from openapi.json — do not edit; regenerate.",
    "",
  ];
  const schemas = spec.components?.schemas ?? {};
  for (const name of Object.keys(schemas).sort(by_code_point)) {
    const s = schemas[name];
    if (s.description) out.push(`/** ${String(s.description).replace(/\*\//g, "* /")} */`);
    out.push(`export interface ${name} ${ts_type({ ...s, type: "object" })}`, "");
  }
  const paths = Object.keys(spec.paths ?? {}).sort(by_code_point);
  const collections = paths.map((p) => COLLECTION_PATH.exec(p)?.[1]).filter(Boolean) as string[];
  out.push(
    `export const COLLECTIONS = ${JSON.stringify(collections)} as const;`,
    "export type Collection = (typeof COLLECTIONS)[number];",
    "",
  );
  const routes: Record<string, string[]> = {};
  for (const p of paths) {
    if (!p.startsWith("/api/tracker/") && p !== "/api/health") continue;
    routes[p] = Object.keys(spec.paths[p])
      .map((m) => m.toUpperCase())
      .sort(by_code_point);
  }
  out.push(`export const ROUTES = ${JSON.stringify(routes)} as const;`, "");
  return out.join("\n");
}

export async function generate(): Promise<string> {
  const spec = JSON.parse(read_text(SPEC));
  // The repo's .prettierrc, so `format:check` and this generator agree on the bytes.
  const config = (await prettier.resolveConfig(OUTPUT)) ?? {};
  return prettier.format(render(spec), { ...config, filepath: OUTPUT });
}

if (import.meta.main) {
  const USAGE = "usage: gen_tm_client.ts [-h] [--check]";
  const args = parse_args(
    USAGE,
    `${USAGE}\n\noptions:\n  -h, --help  show this help message and exit\n  --check     exit 1 if clients/tm/src/api.generated.ts is stale\n`,
    [["--check", "store_true", "check"]],
    { check: false },
  );
  const text = await generate();
  if (args.check) {
    const current = fs.existsSync(OUTPUT) ? read_text(OUTPUT) : null;
    if (current !== text) {
      console.error(
        `❌ ${path.relative(REPO, OUTPUT)} is stale — run: bun scripts/gen_tm_client.ts`,
      );
      process.exit(1);
    }
    console.log(`✅ ${path.relative(REPO, OUTPUT)} matches openapi.json`);
  } else {
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, text);
    console.log(`wrote ${path.relative(REPO, OUTPUT)}`);
  }
}
