#!/usr/bin/env bun
/**
 * Generate the app_settings + app_docs seed migration from a replayed pb_data, so the corpus is regenerable.
 *
 * Bodies are read from the replayed sqlite DB, never by grepping migration source, whose
 * quoting cannot be trusted (.agents/memory/app-docs-quotes-apostrophe-tokenizer.md).
 *
 * With no pb_data_dir it replays pb_migrations/ into a throwaway temp dir and reads the corpus
 * back from there, so regenerating and drift-checking need no pre-existing replay:
 *
 *     bun scripts/gen_app_docs_seed.ts            # regenerate the seed migration
 *     bun scripts/gen_app_docs_seed.ts --check    # refuse if the committed file has drifted
 *     bun scripts/gen_app_docs_seed.ts <pb_data_dir> [-o OUTPUT]
 *
 * BOUND on --check, and it is a large one. The replay applies the generated migration too, and
 * since the baseline collapse that migration is the corpus's ONLY source (replaying without it
 * yields zero app_docs rows), so a hand-edit to a field VALUE in the generated file is
 * self-fulfilling and CANNOT be detected here — measured, not assumed. What --check does catch
 * is drift the replay does not reproduce: a record seeded by some OTHER migration and never
 * regenerated into this file, a hand-reordering (rows render in slug order), a changed field
 * set, and any template or escaping edit. Treat it as generator parity, never as prose
 * integrity; no gate in this repo currently detects a one-byte prose edit to the seed.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { parse_args } from "./_argparse.ts";
import { json_dumps, print, read_text, splitlines, sqlite_connect } from "./_py.ts";
import { repo_root } from "./_repo_root.ts";
import { migrate_up, pb_bin_path } from "./pb_migrate.ts";

export const REPO = repo_root(import.meta.path);
export const PB = pb_bin_path(REPO);
export const MIGRATIONS = path.join(REPO, "pb_migrations");
// The NEWEST app_docs seed migration is the corpus's current source; a re-seed moves this.
// .gitattributes is generated from this constant, so a re-seed moves `merge=binary` onto the new
// seed and the superseded one drops out of it; gen_gitattributes.ts --check blesses that move.
export const DEFAULT_OUTPUT = path.join(REPO, "pb_migrations", "1785186800_seed_app_docs.js");

// `created`/`updated` are autodate fields: seeding them would make every regeneration differ.
export const FIELDS = ["id", "slug", "refName", "title", "body"];

export const TEMPLATE = `/// <reference path="../pb_data/types.d.ts" />
// Seed app_settings and the self-documenting app_docs collection. Idempotent upsert-by-id.
// GENERATED by scripts/gen_app_docs_seed.ts from a replayed pb_data — do not hand-edit.
migrate((app) => {
  const settings = app.findCollectionByNameOrId("app_settings")
  for (const data of [
%settings
  ]) {
    let rec
    try { rec = app.findRecordById("app_settings", data.id) }
    catch (_) { rec = new Record(settings); rec.set("id", data.id) }
    rec.set("key", data.key)
    rec.set("value", data.value)
    app.save(rec)
  }

  const collection = app.findCollectionByNameOrId("app_docs")
  const records = [
%s
  ]

  for (const data of records) {
    let rec
    try { rec = app.findRecordById("app_docs", data.id) }
    catch (_) { rec = new Record(collection); rec.set("id", data.id) }
    rec.set("slug", data.slug)
    rec.set("refName", data.refName)
    rec.set("title", data.title)
    rec.set("body", data.body)
    app.save(rec)
  }
}, (app) => {
  // No-op down: seed data is re-established on any fresh boot.
})
`;

const head = (s: string, n: number): string => [...s].slice(0, n).join("");

/** Every app_settings row as {id, key, value}, value parsed from its stored JSON, ordered by id. */
export function read_settings(data_dir: string): Record<string, unknown>[] {
  const con = sqlite_connect(path.join(data_dir, "data.db"));
  try {
    const rows = con.query("SELECT id, key, value FROM app_settings ORDER BY id").all() as {
      id: string;
      key: string;
      value: unknown;
    }[];
    return rows.map(({ id, key, value }) => ({
      id,
      key,
      value: typeof value === "string" ? JSON.parse(value) : value,
    }));
  } finally {
    con.close();
  }
}

/** Every app_docs row as {field: value}, ordered by slug so a regeneration is byte-stable. */
export function read_records(data_dir: string): Record<string, string>[] {
  const con = sqlite_connect(path.join(data_dir, "data.db"));
  try {
    const rows = con.query(`SELECT ${FIELDS.join(", ")} FROM app_docs ORDER BY slug`).values() as (
      string | null
    )[][];
    return rows.map((row) => Object.fromEntries(FIELDS.map((field, i) => [field, row[i] || ""])));
  } finally {
    con.close();
  }
}

/**
 * The migration source: one record per LINE, each field a plain double-quoted JS string.
 *
 * Per line, because check_keep_in_sync reads a marker's operands off the marker's own line —
 * a single-string corpus hands every body's file names to every other body's marker.
 * Double-quoted, never a template literal (105 of 142 bodies hold a backtick, 2 hold `${`)
 * and never a JSON string parsed at runtime (the double escaping turns every interior quote
 * into `\"`, which that same gate reads as a literal of its own).
 */
export function render(
  records: Record<string, string>[],
  settings: Record<string, unknown>[],
): string {
  const rows = records
    .map(
      (record) =>
        "    { " +
        FIELDS.map(
          (field) => `"${field}": ${json_dumps(record[field]!, { ensure_ascii: true })}`,
        ).join(", ") +
        " },",
    )
    .join("\n");
  const setting_rows = settings
    .map((row) => `    ${json_dumps(row, { ensure_ascii: true })},`)
    .join("\n");
  const [head, tail] = TEMPLATE.split("%settings") as [string, string];
  return head + setting_rows + tail.replace("%s", () => rows);
}

/** Apply `migrations_dir` into a throwaway pb_data and read the corpus back. -> (docs, settings, error). */
export function replay_records(
  migrations_dir: string,
): [Record<string, string>[], Record<string, unknown>[], string] {
  let executable = false;
  try {
    fs.accessSync(PB, fs.constants.X_OK);
    executable = fs.statSync(PB).isFile();
  } catch {}
  if (!executable) return [[], [], `no pocketbase at ${PB} — run \`make pocketbase\`.`];
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "pbgenseed_"));
  try {
    const [ok, out] = migrate_up(PB, tmp, migrations_dir);
    if (!ok) return [[], [], `\`migrate up\` of ${migrations_dir} failed:\n${out}`];
    return [read_records(tmp), read_settings(tmp), ""];
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

/** The first line number where two renderings diverge, with both sides truncated. */
export function first_difference(want: string, got: string): string {
  const want_lines = splitlines(want);
  const got_lines = splitlines(got);
  const n = Math.min(want_lines.length, got_lines.length);
  for (let i = 0; i < n; i++) {
    const a = want_lines[i]!;
    const b = got_lines[i]!;
    if (a !== b) {
      return `line ${i + 1}\n       committed: ${head(b, 160)}\n       regenerated: ${head(a, 160)}`;
    }
  }
  return `committed file has ${got_lines.length} line(s), regenerated has ${want_lines.length}`;
}

// -o help shows the repo-relative default (Python's help embeds the absolute path, which wraps per checkout).
const USAGE = "usage: gen_app_docs_seed.ts [-h] [-o OUTPUT] [--check] [data_dir]";
const HELP = `${USAGE}

Generate the app_docs seed migration from a replayed pb_data, so the corpus is
regenerable.

positional arguments:
  data_dir             a replayed pb_data directory holding data.db (default:
                       replay)

options:
  -h, --help           show this help message and exit
  -o, --output OUTPUT  default:
                       ${path.relative(REPO, DEFAULT_OUTPUT)}
  --check              compare the regenerated text against --output and exit
                       1 on drift, writing nothing

With no data_dir, pb_migrations/ is replayed into a temp dir to produce one.
`;

export function main(): number {
  const args = parse_args(
    USAGE,
    HELP,
    [
      ["data_dir", "store", "data_dir", false],
      ["-o/--output", "store", "output"],
      ["--check", "store_true", "check"],
    ],
    { data_dir: null, output: DEFAULT_OUTPUT, check: false },
  );

  let records: Record<string, string>[];
  let settings: Record<string, unknown>[];
  let source: string;
  if (args.data_dir) {
    if (!fs.statSync(path.join(args.data_dir, "data.db"), { throwIfNoEntry: false })?.isFile()) {
      print(`❌ gen_app_docs_seed: no data.db under ${args.data_dir}`);
      return 1;
    }
    records = read_records(args.data_dir);
    settings = read_settings(args.data_dir);
    source = args.data_dir;
  } else {
    let err: string;
    [records, settings, err] = replay_records(MIGRATIONS);
    if (err) {
      print(`❌ gen_app_docs_seed: ${err}`);
      return 1;
    }
    source = `a replay of ${MIGRATIONS}`;
  }

  if (!records.length) {
    print(`❌ gen_app_docs_seed: ${source} holds no app_docs rows`);
    return 1;
  }

  const rendered = render(records, settings);

  if (args.check) {
    if (!fs.statSync(args.output, { throwIfNoEntry: false })?.isFile()) {
      print(`❌ gen_app_docs_seed --check: ${args.output} does not exist — regenerate it.`);
      return 1;
    }
    const committed = read_text(args.output);
    if (committed !== rendered) {
      print(
        `❌ gen_app_docs_seed --check: ${args.output} has drifted from the corpus ` +
          `${source} produces — first difference at ${first_difference(rendered, committed)}`,
      );
      print("   regenerate with: bun scripts/gen_app_docs_seed.ts");
      return 1;
    }
    print(
      `✅ gen_app_docs_seed --check: ${args.output} matches the ` +
        `${records.length} record(s) a replay produces.`,
    );
    return 0;
  }

  fs.writeFileSync(args.output, rendered);
  print(`✅ gen_app_docs_seed: wrote ${records.length} record(s) to ${args.output}`);
  return 0;
}

if (import.meta.main) {
  process.exit(main());
}
